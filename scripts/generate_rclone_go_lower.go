// Regenerate the rclone lowercase table using the official Go 1.26.5 toolchain:
// GOTOOLCHAIN=go1.26.5 go run scripts/generate_rclone_go_lower.go > Services/CloudConflictNamespace.RcloneLower.g.cs
package main

import (
	"fmt"
	"os"
	"runtime"
	"unicode"
)

type mapping struct {
	from  rune
	delta rune
}

func main() {
	if runtime.Version() != "go1.26.5" || unicode.Version != "15.0.0" {
		fmt.Fprintln(os.Stderr, "expected Go 1.26.5 with Unicode 15.0.0")
		os.Exit(1)
	}

	var mappings []mapping
	for from := rune(0); from <= unicode.MaxRune; from++ {
		if to := unicode.ToLower(from); to != from {
			mappings = append(mappings, mapping{from, to - from})
		}
	}

	fmt.Print(`// Generated by scripts/generate_rclone_go_lower.go using Go 1.26.5 (Unicode 15.0.0).
// See THIRD-PARTY-NOTICES.txt for the Go and Unicode notices.
namespace Jellyfin.Plugin.AudioGateway.Services;

public static partial class CloudConflictNamespace
{
    private static readonly (int First, int Last, int Stride, int Delta)[] RcloneLowerRanges =
    [
`)
	// Combine adjacent mappings with the same delta and spacing. Stride two
	// captures alternating uppercase/lowercase pairs without changing the gaps.
	for first := 0; first < len(mappings); {
		stride := rune(1)
		last := first
		if first+1 < len(mappings) {
			next := mappings[first+1].from - mappings[first].from
			if (next == 1 || next == 2) && mappings[first+1].delta == mappings[first].delta {
				stride = next
				last = first + 1
				for last+1 < len(mappings) && mappings[last+1].delta == mappings[first].delta &&
					mappings[last+1].from-mappings[last].from == stride {
					last++
				}
			}
		}
		fmt.Printf("        (0x%04X, 0x%04X, %d, %d),\n",
			mappings[first].from, mappings[last].from, stride, mappings[first].delta)
		first = last + 1
	}
	fmt.Print("    ];\n}\n")
}
